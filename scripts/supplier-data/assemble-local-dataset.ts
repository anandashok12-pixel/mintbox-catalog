/**
 * Merges catalog-plan.ts + copy/batch-*.json + pricing into the public-safe
 * local dataset the local-only review page renders from
 * (src/data/diwali2026Products.ts). Deliberately excludes every internal field
 * (supplierCost, supplier handle/url) - those live only in
 * scripts/supplier-data/diwali-2026-source.json and copy-input.json, which
 * nothing under src/ ever imports.
 *
 * Usage: npx tsx scripts/supplier-data/assemble-local-dataset.ts
 */
import fs from 'fs'
import path from 'path'
import { CATALOG_PLAN, CATEGORIES } from './catalog-plan'
import copyInput from './copy-input.json'

const COPY_DIR = path.join(__dirname, 'copy')
const OUT_FILE = path.join(__dirname, '..', '..', 'src', 'data', 'diwali2026Products.ts')

interface PricedEntry {
  num: number
  mrp: number
  displayMode: 'fixed' | 'starting-from'
}

interface CopyEntry {
  num: number
  id: string
  shortDescription: string
  description: string
  highlights: string[]
  whatsInTheBox: string[]
  seoTitle: string
  seoDescription: string
  imageAlts: string[]
}

function run() {
  const batchFiles = fs.readdirSync(COPY_DIR).filter(f => f.startsWith('batch-') && f.endsWith('.json'))
  if (batchFiles.length === 0) throw new Error('No copy batch files found in scripts/supplier-data/copy/')

  const copyByNum = new Map<number, CopyEntry>()
  for (const file of batchFiles) {
    const entries: CopyEntry[] = JSON.parse(fs.readFileSync(path.join(COPY_DIR, file), 'utf8'))
    for (const e of entries) {
      if (copyByNum.has(e.num)) throw new Error(`Duplicate copy entry for num ${e.num} (in ${file})`)
      copyByNum.set(e.num, e)
    }
  }

  const missing = CATALOG_PLAN.filter(p => !copyByNum.has(p.num))
  if (missing.length) throw new Error(`Missing copy for: ${missing.map(m => `#${m.num} ${m.slug}`).join(', ')}`)

  const AURADECOR_RE = /aura\s*decor/i
  const EM_DASH_RE = /—/

  const products = CATALOG_PLAN.map(plan => {
    const copy = copyByNum.get(plan.num)!
    const priced = (copyInput as PricedEntry[]).find(c => c.num === plan.num)!
    const category = CATEGORIES.find(c => c.slug === plan.category)
    if (!category) throw new Error(`Unknown category "${plan.category}" for #${plan.num}`)

    const allText = JSON.stringify(copy)
    if (AURADECOR_RE.test(allText)) throw new Error(`SUPPLIER NAME LEAK in copy for #${plan.num} ${plan.slug}: ${allText.match(AURADECOR_RE)}`)
    if (EM_DASH_RE.test(allText)) throw new Error(`EM DASH found in copy for #${plan.num} ${plan.slug}`)

    const imageFiles = Array.from({ length: plan.imagesToUse }, (_, i) => `/catalog/diwali-2026/${plan.slug}/${plan.slug}-${i + 1}.webp`)
    const alts = copy.imageAlts.length === imageFiles.length ? copy.imageAlts : imageFiles.map(() => `${plan.name} - corporate Diwali gift by MintBox`)

    return {
      id: plan.id,
      slug: plan.slug,
      name: plan.name,
      shortDescription: copy.shortDescription,
      description: copy.description,
      highlights: copy.highlights,
      price: priced.mrp,
      displayMode: priced.displayMode,
      moq: plan.moq,
      leadTimeDays: plan.leadTimeDays,
      customisable: plan.customisable,
      inStock: true,
      status: 'draft' as const,
      imageStatus: 'supplier-reference' as const,
      category: { id: category.id, name: category.name, emoji: category.emoji, slug: category.slug },
      features: copy.whatsInTheBox.map(feature => ({ feature })),
      images: imageFiles.map((src, i) => ({ url: src, alt: alts[i] })),
      image: { url: imageFiles[0], alt: alts[0] },
      seoTitle: copy.seoTitle,
      seoDescription: copy.seoDescription,
    }
  })

  const header = `/**
 * Local-only Diwali 2026 catalog dataset (draft review phase).
 * Generated by scripts/supplier-data/assemble-local-dataset.ts - do not hand-edit,
 * re-run the generator instead. Contains no supplier-identifying data; internal
 * cost/supplier fields live only in scripts/supplier-data/ and are never imported
 * from here.
 */
import type { DiwaliCategory } from '@/components/content/DiwaliHamperShowcase'

export type Diwali2026Category = DiwaliCategory

export interface Diwali2026Product {
  id: string
  slug: string
  name: string
  shortDescription: string
  description: string
  highlights: string[]
  price: number
  displayMode: 'fixed' | 'starting-from'
  moq: number
  leadTimeDays: number
  customisable: boolean
  inStock: boolean
  status: 'draft'
  imageStatus: 'supplier-reference' | 'mintbox-owned'
  category: Diwali2026Category
  features: { feature: string }[]
  images: { url: string; alt: string }[]
  image: { url: string; alt: string }
  seoTitle: string
  seoDescription: string
}

export const DIWALI_2026_CATEGORIES: Diwali2026Category[] = ${JSON.stringify(CATEGORIES.map(c => ({ id: c.id, name: c.name, emoji: c.emoji, slug: c.slug })), null, 2)}

export const DIWALI_2026_PRODUCTS: Diwali2026Product[] = ${JSON.stringify(products, null, 2)}
`

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, header)
  console.log(`Wrote ${products.length} products to ${OUT_FILE}`)
}

run()
